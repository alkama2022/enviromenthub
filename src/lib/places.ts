export interface OpeningHours {
  /** Human readable summary, e.g. "Mon–Sat 08:00–18:00". */
  summary: string;
  /** 24h open range used for a coarse "open now" estimate. null = 24 hours. */
  opens: number | null;
  closes: number | null;
  /** Days of week the place opens: 0 = Sunday. */
  days: number[];
}

export interface Place {
  id: string;
  name: string;
  category: PlaceCategory;
  subtype: string;
  ownership: "Public" | "Private" | "Community";
  locationSlug: string;
  area: string;
  address: string;
  coords: [number, number];
  description: string;
  services: string[];
  /** Free-text tags used by the intent matcher (needs, occasions, audiences). */
  tags: string[];
  hours: OpeningHours;
  phone: string | null;
  website: string | null;
  rating: { value: number; count: number; source: string } | null;
  priceLevel: 1 | 2 | 3 | 4 | null;
  accessibility: string[];
  emergency: boolean;
  source: SourceInfo;
  verified: string;
}

const DIR = (date: string): SourceInfo => ({
  name: "Sample place directory (demo dataset)",
  date,
});

const ALL_WEEK = [0, 1, 2, 3, 4, 5, 6];
const MON_SAT = [1, 2, 3, 4, 5, 6];

const H = (summary: string, opens: number | null, closes: number | null, days = ALL_WEEK): OpeningHours => ({
  summary,
  opens,
  closes,
  days,
});

const ALWAYS = H("Open 24 hours, every day", null, null, ALL_WEEK);

type Seed = Omit<Place, "id" | "source" | "verified">;

function build(seeds: Seed[]): Place[] {
  return seeds.map((s, i) => ({
    ...s,
    id: `${s.locationSlug}-${s.category}-${i}`,
    source: DIR("Aug 2026"),
    verified: "Sample record — not verified against an official registry",
  }));
}

