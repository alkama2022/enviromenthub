export const PLACES: Place[] = build(SEEDS);

export function placesForLocation(slug: string): Place[] {
  return PLACES.filter((p) => p.locationSlug === slug);
}

export function isOpenNow(hours: OpeningHours, now = new Date()): boolean | null {
  if (hours.opens === null && hours.closes === null) return true;
  if (hours.opens === null || hours.closes === null) return null;
  if (!hours.days.includes(now.getDay())) return false;
  const h = now.getHours() + now.getMinutes() / 60;
  return h >= hours.opens && h < hours.closes;
}

export function priceLabel(level: Place["priceLevel"]): string {
  if (level === null) return "Price information unavailable";
  return ["Low cost", "Moderate", "Higher cost", "Premium"][level - 1] ?? "Unavailable";
}
